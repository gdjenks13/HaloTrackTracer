// Rebuilds track-tracer-prefabs.js, the prefabs the Track Tracer offers as built-in jump markers.
// Run it again whenever you change one of these prefabs in Halo Map Studio:
//   node update-default-prefabs.js
// A page opened from disk cannot read other files, so the prefabs are copied into a script file.
const fs = require("fs"), path = require("path");

const NAMES = ["Whoop", "SmallLanding", "SmallJump", "Turn_Normal180_1", "StartGate_1"];
const PREFAB_DIR = path.join(process.env.LOCALAPPDATA || "", "HaloMapStudio", "prefabs");
const CATALOG = path.join(__dirname, "..", "HaloMapStudio", "crates", "hms-app", "src", "xgame", "catalog.json");
const TARGET = "dlc_forge_island";

// Pieces saved on another map carry that map's identity. The tracer exports a Forge Island
// prefab, so each such piece is switched to the same piece on Forge Island, using HMS's catalog.
const catalog = fs.existsSync(CATALOG) ? JSON.parse(fs.readFileSync(CATALOG, "utf8")).objects : [];
const onTarget = catalog.filter(o => o.game === "halo4" && (o.places || []).some(p => p.startsWith(TARGET + ":")));
function toTarget(o) {
  const entry = String(o.display || "").split(":")[0];
  const hits = onTarget.filter(c => c.variant === o.variant && (!entry || c.entry === entry) && c.dims && c.dims[0] > 0.11);
  const hit = hits.find(c => c.category === "ff_structure") || hits[0];
  if (!hit) return null;
  return { ...o, key: hit.key, tag: hit.tag, spot: hit.places.find(p => p.startsWith(TARGET + ":")).split(":").slice(1).map(Number) };
}

const out = [], report = [];
for (const name of NAMES) {
  const file = path.join(PREFAB_DIR, name + ".hmsprefab");
  if (!fs.existsSync(file)) { report.push(`MISSING  ${file}`); continue; }
  const pf = JSON.parse(fs.readFileSync(file, "utf8"));
  let switched = 0; const unmatched = new Set();
  const objects = pf.objects.map(o => {
    if (pf.canvas === TARGET) return o;
    const t = toTarget(o);
    if (t) { switched++; return t; }
    unmatched.add(o.display || o.variant || o.key); return o;
  });
  out.push({ name: pf.name || name, game: pf.game, canvas: unmatched.size ? pf.canvas : TARGET, objects });
  const physics = {}; for (const o of objects) { const k = `${o.placement}`; physics[k] = (physics[k] || 0) + 1; }
  report.push(`${name}: ${objects.length} objects, from ${pf.canvas}` + (switched ? `, ${switched} switched to Forge Island pieces` : "") +
    (unmatched.size ? `, NOT FOUND on Forge Island: ${[...unmatched].join(", ")}` : "") + `, placement values ${JSON.stringify(physics)}`);
}
const js = "// Built-in jump-marker prefabs. Generated by update-default-prefabs.js; do not edit by hand.\n" +
  "const DEFAULT_PREFABS = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(__dirname, "track-tracer-prefabs.js"), js);
console.log(report.join("\n"));
console.log(`Wrote track-tracer-prefabs.js (${out.length} prefabs, ${js.length} bytes)`);
